#!/usr/bin/env python3
"""Embed standalone KCL sources in the installable bundled Compositions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(component, api_version, kind, name):
    header = f'''# Generated by scripts/generate_composition.py; edit functions/{component}/main.k.
apiVersion: apiextensions.crossplane.io/v1
kind: Composition
metadata:
  name: {name}
spec:
  compositeTypeRef:
    apiVersion: {api_version}
    kind: {kind}
  mode: Pipeline
  pipeline:
  - step: compose
    functionRef:
      name: crossplane-contrib-function-kcl
    input:
      apiVersion: krm.kcl.dev/v1alpha1
      kind: KCLInput
      spec:
        source: |
'''
    source = (ROOT / f'functions/{component}/main.k').read_text()
    embedded = ''.join('          ' + line if line.strip() else '\n' for line in source.splitlines(keepends=True))
    return header + embedded + '''  - step: automatically-detect-ready-composed-resources
    functionRef:
      name: crossplane-contrib-function-auto-ready
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    components = json.loads((ROOT / 'third_party/sources.json').read_text())
    components.append({'component': 'xcluster', 'apiVersion': 'caas.upbound.io/v1alpha1',
                       'kind': 'XCluster', 'composition': 'xclusters.caas.upbound.io'})
    for item in components:
        component = item['component']
        output = ROOT / ('apis/composition.yaml' if component == 'xcluster' else f'apis/{component}/composition.yaml')
        expected = generate(component, item['apiVersion'], item['kind'], item['composition'])
        if args.check:
            if output.read_text() != expected:
                raise SystemExit(f'{output.relative_to(ROOT)} is stale; run make generate')
        else:
            output.write_text(expected)
